export const EXPRESSION_LABELS = { link: '연결어', stance: '태도·강조', hedge: '추측·완곡', idiom: '관용 표현', grammar: '고급 문법' };

// 답변 속 고급 표현 찾기 — 긴 표현을 먼저 찾고 겹치는 위치는 한 번만. 반환: 나온 순서대로 [{ start, end, text, ko, c }]
export function findExpressions(text) {
  const s = String(text || '');
  const cands = [];
  for (const e of EXPRESSIONS) for (const p of e.p || []) cands.push({ p, e });
  cands.sort((a, b) => b.p.length - a.p.length);
  // 형태가 바뀌는 구문(정규식)은 고정 문구 다음에 시도 — 고정 문구가 우선
  for (const e of EXPRESSIONS) if (e.re) cands.push({ re: e.re, e });
  const taken = [];
  const out = [];
  const usedEntry = new Set();
  for (const { p, re: pattern, e } of cands) {
    if (usedEntry.has(e)) continue;
    const body = pattern || p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp('(^|[^A-Za-z\'])(' + body + ')(?![A-Za-z])', e.cs ? '' : 'i'); // cs: 대소문자 구분 (문장 첫머리 표현)
    const m = re.exec(s);
    if (!m) continue;
    const start = m.index + m[1].length;
    const end = start + m[2].length;
    if (taken.some(([a, b]) => start < b && end > a)) continue;
    taken.push([start, end]);
    usedEntry.add(e);
    out.push({ start, end, text: s.slice(start, end), ko: e.ko, c: e.c });
  }
  return out.sort((a, b) => a.start - b.start);
}
